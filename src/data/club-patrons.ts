export function getTopClubPatrons(clubId: string, limit = 10) {
  return clubPatrons
    .filter((p) => p.clubId === clubId)
    .sort((a, b) => b.totalContributed - a.totalContributed)
    .slice(0, limit);
}

export function getRecentClubShoppers(clubId: string, limit = 5) {
  return clubPatrons
    .filter((p) => p.clubId === clubId && p.lastPurchaseAt)
    .sort((a, b) =>
      (b.lastPurchaseAt ?? "").localeCompare(a.lastPurchaseAt ?? ""),
    )
    .slice(0, limit);
}

export const FEATURED_CLUB_SLUGS = [
  "bayern-munich",
  "borussia-dortmund",
  "werder-bremen",
  "fc-lorient",
] as const;

export function getClubById(id: string) {
  return clubs.find((c) => c.id === id);
}

export function getClubBySlug(slug: string) {
  return clubs.find((c) => c.slug === slug);
}

export function isFeaturedClub(slug: string) {
  return (FEATURED_CLUB_SLUGS as readonly string[]).includes(slug);
}

export function getFeaturedClubs() {
  return FEATURED_CLUB_SLUGS.map((slug) => getClubBySlug(slug)).filter(
    (c): c is NonNullable<typeof c> => Boolean(c),
  );
}
